$$;
-- Transfers use the same account and pair revisions as the existing marketplace.
-- This routine never trusts a client-supplied balance, item payload or price.
create or replace function public.runner_club_transfer(p_user text,p_token text,p_action text,p_data jsonb)
returns jsonb language plpgsql security definer set search_path=public set lock_timeout='1500ms' as $$
declare a public.accounts%rowtype;pr public.pairs%rowtype;ps public.pair_play_state%rowtype;
 c public.runner_clubs%rowtype;m public.runner_club_members%rowtype;
 w jsonb;s jsonb;item jsonb;items jsonb;old_receipt jsonb;path text[];key text;kind text;slot text;label text;
 qty bigint;available numeric;cash numeric;stored numeric;gid bigint;capacity integer;delta integer;points integer;
 request_key text;signature jsonb;actor_name text;today date=(now() at time zone 'Asia/Seoul')::date;
begin
 if not exists(select 1 from public.accounts where id=p_user and pw=p_token) then raise exception 'CLUB_AUTH';end if;
 request_key=coalesce(p_data->>'request','');signature=jsonb_build_object('action',p_action,'data',p_data-'directory'-'after'-'request');
 if char_length(request_key) not between 8 and 100 then raise exception '요청 번호가 필요합니다.';end if;
 -- Same lock order as pair_play: pair advisory lock, pair, shared state, accounts.
 select * into pr from public.pairs where status='accepted' and p_user in(from_id,to_id) order by id desc limit 1;
 if found then
  if not pg_try_advisory_xact_lock(pr.id) then raise exception '공동 저장을 반영 중입니다. 잠시 후 다시 시도해 주세요.';end if;
  select * into pr from public.pairs where id=pr.id and status='accepted' for update;
  select * into ps from public.pair_play_state where pair_id=pr.id for update;
  if ps.pair_id is null or ps.closed then raise exception '공동 지갑을 연결한 뒤 창고를 이용해 주세요.';end if;
  perform 1 from public.accounts where id in(pr.from_id,pr.to_id) order by id for update;
 else perform 1 from public.accounts where id=p_user for update;
 end if;
 select * into a from public.accounts where id=p_user;
 actor_name=coalesce(nullif(a.name,''),a.id);
 select rr.signature into old_receipt from public.runner_club_receipts rr where rr.user_id=p_user and rr.request_id=request_key;
 if found then
  if old_receipt<>signature then raise exception '다른 작업에 사용된 요청 번호입니다.';end if;
  return jsonb_build_object('ok',true,'replayed',true,'inventory',public.runner_club_inventory(a.save));
 end if;
 -- Lock membership first, then its club; the main RPC uses the same ordering.
 perform pg_advisory_xact_lock(hashtextextended('runner-club:'||p_user,0));
 select * into m from public.runner_club_members where user_id=p_user;
 if not found then raise exception '모임에 먼저 가입해 주세요.';end if;
 if coalesce(p_data->>'club','')<>m.club_id::text then raise exception '모임이 바뀌었습니다. 다시 확인해 주세요.';end if;
 select * into c from public.runner_clubs where id=m.club_id for update;
 if not exists(select 1 from public.runner_club_members where user_id=p_user and club_id=c.id) then raise exception '모임 가입 상태가 변경되었습니다.';end if;
 if ps.pair_id is not null then w=ps.wallet;s=public.pp_apply(a.save,w,ps.progress);
 else s=a.save;w=public.pp_wallet(s);end if;
 if s is null then raise exception '캐릭터 저장 기록이 필요합니다.';end if;
 qty=coalesce((p_data->>'qty')::bigint,0);kind=coalesce(p_data->>'kind','');key=coalesce(p_data->>'key','');
 if p_action in('deposit','withdraw') and (qty<1 or qty>1000000000) then raise exception '수량은 1~10억 사이의 정수여야 합니다.';end if;
 if p_action='withdraw' and c.owner_id<>p_user and not m.can_withdraw then raise exception '모임장이 부여한 창고 출납 권한이 필요합니다.';end if;
 items=coalesce(c.vault->'items','{}');cash=coalesce((w->>'rin')::numeric,0);stored=coalesce((c.vault->>'rin')::numeric,0);
 if p_action='donate' then
  points=(p_data->>'points')::integer;
  if points not in(10,50,200) then raise exception '기부 점수를 확인해 주세요.';end if;
  if m.donated_day is distinct from today then m.donated=0;end if;
  if m.donated+points>200 then raise exception '하루 기부 한도는 200점입니다.';end if;
  qty=points*474;
  if cash<qty then raise exception '륜이 부족합니다.';end if;
  cash=cash-qty;stored=stored+qty;c.xp=c.xp+points;
  update public.runner_club_members set donated_day=today,donated=m.donated+points,contribution=contribution+points where user_id=p_user;
  label='기부 '||qty||'륜 · 기여도 +'||points;
 elsif p_action='room_upgrade' then
  if c.owner_id<>p_user then raise exception '모임장만 모임방을 확장할 수 있습니다.';end if;
  if c.room_lv>=5 then raise exception '모임방은 이미 최고 단계입니다.';end if;
  qty=c.room_lv*10000;
  if stored<qty then raise exception '모임 금고의 륜이 부족합니다.';end if;
  stored=stored-qty;c.room_lv=c.room_lv+1;label='모임방 Lv '||c.room_lv||' 확장 · 금고 -'||qty||'륜';
 elsif kind='rin' then
  if p_action='deposit' then
   if cash<qty then raise exception '소지한 륜이 부족합니다.';end if;cash=cash-qty;stored=stored+qty;
  elsif p_action='withdraw' then
   if stored<qty then raise exception '금고의 륜이 부족합니다.';end if;stored=stored-qty;cash=cash+qty;
  else raise exception '잘못된 창고 작업입니다.';end if;
  label=case when p_action='deposit' then '금고 입금 ' else '금고 출금 ' end||qty||'륜';
 elsif p_action in('deposit','withdraw') then
  if p_action='withdraw' then
   slot=key;item=items->slot;
   if item is null then raise exception '창고 물품이 없습니다.';end if;
   kind=item->>'kind';key=item->>'key';
  else slot=kind||':'||key;end if;
  path=case kind when 'material' then array['mat',key] when 'ingredient' then array['ing',key]
    when 'building' then array['bmat',key] when 'crop' then array['ingredients',key]
    when 'potion' then array['potion',key] when 'seed' then array['seeds',key]
    when 'dish' then array['dishes',key] else null end;
  if kind='gear' then
   if qty<>1 then raise exception '법구는 한 번에 한 개씩 옮길 수 있습니다.';end if;
   if p_action='deposit' then
    select value into item from jsonb_array_elements(coalesce(w->'bag','[]')) where value->>'id'=key;
    if not found then raise exception '바랑에 없는 법구입니다.';end if;
    if coalesce((item->>'bound')::boolean,false) or coalesce((item->>'locked')::boolean,false) or coalesce((item->>'lock')::boolean,false) then raise exception '귀속·잠금 법구는 넣을 수 없습니다.';end if;
    if item->>'slot' not in('robe','cap','charm','sutra') then raise exception '보관할 수 없는 법구입니다.';end if;
    w=jsonb_set(w,'{bag}',(select coalesce(jsonb_agg(value),'[]') from jsonb_array_elements(w->'bag') where value->>'id'<>key));
    label=coalesce(item->>'name','법구');slot='gear:'||nextval('public.runner_club_gear_seq');
    item=jsonb_build_object('kind','gear','key',key,'name',label,'qty',1,'gear',item);
   else
    capacity=case when ps.pair_id is not null then greatest(80,coalesce((a.save->>'pairBagCap')::integer,80)) else 40+coalesce((s#>>'{res,r11}')::integer,0)*5 end;
    if jsonb_array_length(coalesce(w->'bag','[]'))>=capacity then raise exception '바랑이 가득 찼습니다.';end if;
    gid=greatest(coalesce((w->>'gid')::bigint,1),(select coalesce(max((value->>'id')::bigint),0)+1 from jsonb_array_elements(coalesce(w->'bag','[]'))));
    w=jsonb_set(w,'{bag}',coalesce(w->'bag','[]')||jsonb_build_array((item->'gear')||jsonb_build_object('id',gid)));
    w=jsonb_set(w,'{gid}',to_jsonb(gid+1));label=item->>'name';
   end if;
  elsif path is not null and char_length(key) between 1 and 100 then
   available=coalesce((w#>>path)::numeric,0);
   if p_action='deposit' then
    if available<qty then raise exception '소지품 수량이 부족합니다.';end if;
    label=left(coalesce(nullif(p_data->>'name',''),key),80);
    item=coalesce(items->slot,jsonb_build_object('kind',kind,'key',key,'name',label,'qty',0));
    item=jsonb_set(item,'{qty}',to_jsonb(coalesce((item->>'qty')::numeric,0)+qty));delta=-1;
   else
    if coalesce((item->>'qty')::numeric,0)<qty then raise exception '창고 수량이 부족합니다.';end if;
    if kind='seed' and qty>10 then raise exception '씨앗은 하루 10개까지 꺼낼 수 있습니다.';end if;
    if kind='seed' and (select coalesce(sum((regexp_match(lg.body,'수량 ([0-9]+)'))[1]::int),0) from public.runner_club_logs lg where lg.club_id=c.id and lg.user_id=p_user and lg.kind='seed_withdraw' and (lg.created_at at time zone 'Asia/Seoul')::date=today)+qty>10 then raise exception '오늘 씨앗 꺼내기 한도(10개)를 넘었습니다.';end if;
    if kind<>'seed' and qty>99 then raise exception '물품은 한 번에 99개까지 꺼낼 수 있습니다.';end if;
    label=item->>'name';item=jsonb_set(item,'{qty}',to_jsonb((item->>'qty')::numeric-qty));delta=1;
   end if;
   w=jsonb_set(w,array[path[1]],coalesce(w->path[1],'{}'));
   w=jsonb_set(w,path,to_jsonb(available+delta*qty));
  else raise exception '지원하지 않는 창고 품목입니다.';end if;
  if p_action='deposit' then
   if not items ? slot and (select count(*) from jsonb_object_keys(items))>=60+(c.room_lv-1)*10 then raise exception '공용 창고가 가득 찼습니다.';end if;
   items=jsonb_set(items,array[slot],item);
  elsif kind='gear' or (item->>'qty')::numeric=0 then items=items-slot;
  else items=jsonb_set(items,array[slot],item);end if;
  label=case when p_action='deposit' then '창고 넣기 · ' else '창고 꺼내기 · ' end||label||' · 수량 '||qty;
 else raise exception '잘못된 창고 작업입니다.';end if;
 if cash>1000000000000000 or stored>1000000000000000 then raise exception '보관 가능한 륜 한도를 초과합니다.';end if;
 w=jsonb_set(w,'{rin}',to_jsonb(cash));
 update public.runner_clubs set vault=jsonb_build_object('rin',stored,'items',items),xp=c.xp,room_lv=c.room_lv where id=c.id;
 if ps.pair_id is not null then
  update public.pair_play_state set wallet=w,revision=revision+1 where pair_id=ps.pair_id;
  update public.accounts set save=public.pp_apply(save,w,ps.progress)||jsonb_build_object('marketRev',market_rev+1),market_rev=market_rev+1,pair_play_rev=pair_play_rev+1 where id in(pr.from_id,pr.to_id);
 else
  s=public.pp_apply(s,w,public.pp_progress(s));
  update public.accounts set save=s||jsonb_build_object('marketRev',market_rev+1,'pairSoloRev',pair_play_rev+1),market_rev=market_rev+1,pair_play_rev=pair_play_rev+1 where id=p_user;
 end if;
 insert into public.runner_club_logs(club_id,user_id,who,kind,body) values(c.id,p_user,actor_name,case when kind='seed' and p_action='withdraw' then 'seed_withdraw' else p_action end,label);
 insert into public.runner_club_receipts(user_id,request_id,signature) values(p_user,request_key,signature);
 select save into s from public.accounts where id=p_user;
 return jsonb_build_object('ok',true,'inventory',public.runner_club_inventory(s));
end $$;
