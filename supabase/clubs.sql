-- 사용자 모임·출석 성장·부원 전용 채팅. Supabase SQL Editor에서 한 번 실행.
-- 기존 계정/페어/공용 채팅/재화는 변경하지 않습니다. 재실행 가능.
begin;
create table if not exists public.runner_clubs(
 id bigint generated by default as identity primary key,
 name text not null check(char_length(name) between 2 and 20),
 intro text not null default '' check(char_length(intro)<=200),
 owner_id text not null references public.accounts(id),
 xp integer not null default 0 check(xp>=0),created_at timestamptz not null default now()
);
create unique index if not exists runner_clubs_name_idx on public.runner_clubs(lower(name));
create table if not exists public.runner_club_members(
 user_id text primary key references public.accounts(id) on delete cascade,
 club_id bigint not null references public.runner_clubs(id) on delete cascade,
 joined_at timestamptz not null default now(),attended date,contribution integer not null default 0
);
create index if not exists runner_club_members_club_idx on public.runner_club_members(club_id);
create table if not exists public.runner_club_messages(
 id bigint generated by default as identity primary key,
 club_id bigint not null references public.runner_clubs(id) on delete cascade,
 from_id text not null references public.accounts(id),who text not null,
 body text not null check(char_length(body) between 1 and 1000),
 mode text not null check(mode in('RP','오너')),created_at timestamptz not null default now(),
 request_id text not null,unique(from_id,request_id)
);
create index if not exists runner_club_messages_history_idx on public.runner_club_messages(club_id,id desc);
alter table public.runner_clubs enable row level security;
alter table public.runner_club_members enable row level security;
alter table public.runner_club_messages enable row level security;
revoke all on public.runner_clubs,public.runner_club_members,public.runner_club_messages from anon,authenticated;
create or replace function public.runner_club(p_user text,p_token text,p_action text default 'snapshot',p_data jsonb default '{}')
returns jsonb language plpgsql security definer set search_path=public set lock_timeout='1500ms' as $$
declare c public.runner_clubs%rowtype;m public.runner_club_members%rowtype;
 actor_name text;new_name text;new_intro text;target bigint;successor text;today date=(now() at time zone 'Asia/Seoul')::date;
 clubs jsonb;mine jsonb;members jsonb;messages jsonb;last_id bigint;body_text text;request_key text;
begin
 select coalesce(nullif(name,''),id) into actor_name from public.accounts where id=p_user and pw=p_token;
 if not found then raise exception 'CLUB_AUTH';end if;
 if p_action not in('snapshot','create','join','leave','attend','message') then raise exception 'CLUB_ACTION';end if;
 if p_action<>'snapshot' then perform pg_advisory_xact_lock(hashtextextended('runner-club:'||p_user,0));end if;
 select * into m from public.runner_club_members where user_id=p_user;
 if p_action='create' then
  new_name=btrim(coalesce(p_data->>'name',''));new_intro=btrim(coalesce(p_data->>'intro',''));
  if char_length(new_name) not between 2 and 20 or char_length(new_intro)>200 then raise exception '모임 이름은 2~20자, 소개는 200자까지 입력해 주세요.';end if;
  if m.user_id is not null then
   if not exists(select 1 from public.runner_clubs where id=m.club_id and owner_id=p_user and name=new_name) then raise exception '이미 가입한 모임이 있습니다.';end if;
  else
   insert into public.runner_clubs(name,intro,owner_id) values(new_name,new_intro,p_user) returning * into c;
   insert into public.runner_club_members(user_id,club_id) values(p_user,c.id);
  end if;
 elsif p_action='join' then
  target=(p_data->>'id')::bigint;
  if m.user_id is not null and m.club_id<>target then raise exception '현재 모임을 탈퇴한 뒤 가입해 주세요.';end if;
  select * into c from public.runner_clubs where id=target for update;
  if not found then raise exception '존재하지 않는 모임입니다.';end if;
  if m.user_id is null then
   if (select count(*) from public.runner_club_members where club_id=target)>=4 then raise exception '모임 정원(4명)이 가득 찼습니다.';end if;
   insert into public.runner_club_members(user_id,club_id) values(p_user,target);
  end if;
 elsif p_action='leave' then
  if m.user_id is not null then
   select * into c from public.runner_clubs where id=m.club_id for update;
   delete from public.runner_club_members where user_id=p_user;
   if c.owner_id=p_user then
    select user_id into successor from public.runner_club_members where club_id=c.id order by joined_at,user_id limit 1;
    if successor is null then delete from public.runner_clubs where id=c.id;
    else update public.runner_clubs set owner_id=successor where id=c.id;end if;
   end if;
  end if;
 elsif p_action='attend' then
  if m.user_id is null then raise exception '모임에 먼저 가입해 주세요.';end if;
  perform 1 from public.runner_clubs where id=m.club_id for update;
  if m.attended is distinct from today then
   update public.runner_club_members set attended=today,contribution=contribution+10 where user_id=p_user;
   update public.runner_clubs set xp=xp+10 where id=m.club_id;
  end if;
 elsif p_action='message' then
  if m.user_id is null then raise exception '모임 부원만 채팅할 수 있습니다.';end if;
  -- A stale composer must never send into a newly joined group.
  if coalesce(p_data->>'club','')<>m.club_id::text then raise exception '모임이 바뀌었습니다. 채팅창을 다시 열어 주세요.';end if;
  body_text=btrim(coalesce(p_data->>'body',''));request_key=coalesce(p_data->>'request','');
  if char_length(body_text) not between 1 and 1000 or char_length(request_key) not between 8 and 100 then raise exception '메시지는 1~1000자까지 입력해 주세요.';end if;
  if not exists(select 1 from public.runner_club_messages where from_id=p_user and request_id=request_key) then
   if (select count(*) from public.runner_club_messages where from_id=p_user and created_at>now()-interval '10 seconds')>=10 then raise exception '잠시 후 다시 보내 주세요.';end if;
   insert into public.runner_club_messages(club_id,from_id,who,body,mode,request_id)
   values(m.club_id,p_user,actor_name,body_text,case when p_data->>'mode'='오너' then '오너' else 'RP' end,request_key);
  end if;
 end if;
 select * into m from public.runner_club_members where user_id=p_user;
 if coalesce((p_data->>'directory')::boolean,false) then
 select coalesce(jsonb_agg(to_jsonb(q) order by q.id desc),'[]') into clubs from
 (select rc.id,rc.name,rc.intro,rc.owner_id,rc.xp,least(10,1+rc.xp/100) as lv,count(cm.user_id) as members
 from public.runner_clubs rc left join public.runner_club_members cm on cm.club_id=rc.id group by rc.id order by rc.id desc limit 200) q;
 end if;
 if m.user_id is not null then
  select to_jsonb(q) into mine from (select rc.id,rc.name,rc.intro,rc.owner_id,rc.xp,least(10,1+rc.xp/100) as lv,m.contribution,m.attended=today as attended from public.runner_clubs rc where id=m.club_id) q;
  select coalesce(jsonb_agg(to_jsonb(q) order by q.joined_at,q.user_id),'[]') into members from
  (select cm.user_id,coalesce(nullif(a.name,''),a.id) as name,cm.joined_at,cm.contribution from public.runner_club_members cm join public.accounts a on a.id=cm.user_id where cm.club_id=m.club_id) q;
  last_id=case when p_data->>'club'=m.club_id::text then greatest(0,coalesce((p_data->>'after')::bigint,0)) else 0 end;
  select coalesce(jsonb_agg(to_jsonb(q) order by q.id),'[]') into messages from
  (select id,club_id,from_id,who,body,mode,created_at from public.runner_club_messages where club_id=m.club_id and id>last_id order by id desc limit 120) q;
 end if;
 return jsonb_build_object('ok',true,'clubs',clubs,'mine',mine,'members',coalesce(members,'[]'),'messages',coalesce(messages,'[]'));
end $$;
revoke all on function public.runner_club(text,text,text,jsonb) from public;
grant execute on function public.runner_club(text,text,text,jsonb) to anon,authenticated;
notify pgrst,'reload schema';
commit;
