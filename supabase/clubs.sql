create or replace function public.runner_club(p_user text,p_token text,p_action text default 'snapshot',p_data jsonb default '{}')
returns jsonb language plpgsql security definer set search_path=public set lock_timeout='1500ms' as $$
declare c public.runner_clubs%rowtype;m public.runner_club_members%rowtype;before_member public.runner_club_members%rowtype;
 r jsonb;extra jsonb='{}';inventory jsonb;roster jsonb;directory jsonb;pending jsonb;posts jsonb;logs jsonb;
 actor_name text;target text;message_text text;kind text;nonce text;pid bigint;parent bigint;today date=(now() at time zone 'Asia/Seoul')::date;
 detail boolean=coalesce((p_data->>'directory')::boolean,false);
begin
 select coalesce(nullif(name,''),id) into actor_name from public.accounts where id=p_user and pw=p_token;
 if not found then raise exception 'CLUB_AUTH';end if;
 if p_action in('deposit','withdraw','donate','room_upgrade') then
  r=public.runner_club_transfer(p_user,p_token,p_action,p_data);inventory=r->'inventory';
 else
  if p_action<>'snapshot' and p_action<>'inspect' then perform pg_advisory_xact_lock(hashtextextended('runner-club:'||p_user,0));end if;
  select * into m from public.runner_club_members where user_id=p_user;before_member=m;
  if p_action='join' then
   if m.user_id is not null and m.club_id<>(p_data->>'id')::bigint then raise exception '현재 모임을 탈퇴한 뒤 가입해 주세요.';end if;
   select * into c from public.runner_clubs where id=(p_data->>'id')::bigint for update;
   if not found then raise exception '존재하지 않는 모임입니다.';end if;
   if m.user_id is null and c.join_mode<>'open' then
    if c.join_mode='closed' then raise exception '지금은 모임원을 모집하지 않습니다.';end if;
    if (select count(*) from public.runner_club_members where club_id=c.id)>=4 then raise exception '모임 정원(4명)이 가득 찼습니다.';end if;
    insert into public.runner_club_requests(club_id,user_id) values(c.id,p_user) on conflict do nothing;
    message_text='가입 신청을 보냈습니다. 모임장 승인을 기다려 주세요.';kind='apply';
   else
    perform public.runner_club_core(p_user,p_token,'join',p_data);
    if before_member.user_id is null then message_text=actor_name||' 님이 가입했습니다.';kind='join';end if;
    delete from public.runner_club_requests where user_id=p_user;
   end if;
  elsif p_action in('create','attend','leave') then
   if p_action='leave' and m.user_id is not null then
    select * into c from public.runner_clubs where id=m.club_id for update;
    if (select count(*) from public.runner_club_members where club_id=c.id)=1 and
      (coalesce((c.vault->>'rin')::numeric,0)>0 or c.vault->'items'<>'{}'::jsonb) then raise exception '마지막 부원은 공용 금고와 창고를 비운 뒤 탈퇴해 주세요.';end if;
   end if;
   perform public.runner_club_core(p_user,p_token,p_action,p_data);
   if p_action='create' and before_member.user_id is null then message_text=actor_name||' 님이 모임을 만들었습니다.';kind='create';
   elsif p_action='attend' and before_member.attended is distinct from today then message_text=actor_name||' 님 출석 · 경험치 +10';kind='attend';
   elsif p_action='leave' and before_member.user_id is not null then message_text=actor_name||' 님이 탈퇴했습니다. 모임장 승계는 남은 부원에게 자동 반영됩니다.';kind='leave';end if;
  elsif p_action='message' then perform public.runner_club_core(p_user,p_token,p_action,p_data);
  elsif p_action='inspect' then
   select jsonb_build_object('id',rc.id,'name',rc.name,'intro',rc.intro,'lv',least(10,1+rc.xp/100),'members',(select count(*) from public.runner_club_members where club_id=rc.id),'join_mode',rc.join_mode) into extra from public.runner_clubs rc where rc.id=(p_data->>'id')::bigint;
   extra=jsonb_build_object('preview',extra);
  elsif p_action in('cancel_apply','edit','approve','reject','permissions','transfer_lead','kick','post','delete_post','room_edit') then
   if p_action='cancel_apply' then delete from public.runner_club_requests where user_id=p_user and club_id=(p_data->>'id')::bigint;
   else
    if m.user_id is null then raise exception '모임에 먼저 가입해 주세요.';end if;
    select * into c from public.runner_clubs where id=m.club_id for update;
    if not exists(select 1 from public.runner_club_members where user_id=p_user and club_id=c.id) then raise exception '모임 가입 상태가 변경되었습니다.';end if;
    if p_action not in('post','delete_post') and c.owner_id<>p_user then raise exception '모임장만 변경할 수 있습니다.';end if;
    target=coalesce(p_data->>'user','');
    if p_action='edit' then
     if char_length(coalesce(p_data->>'notice',''))>1000 or char_length(coalesce(p_data->>'intro',''))>200 or coalesce(p_data->>'join_mode','') not in('open','approval','closed') then raise exception '공지·소개 또는 가입 방식을 확인해 주세요.';end if;
     update public.runner_clubs set notice=p_data->>'notice',intro=p_data->>'intro',join_mode=p_data->>'join_mode' where id=c.id;message_text='공지·소개·가입 방식을 변경했습니다.';kind='manage';
    elsif p_action='approve' then
     if not exists(select 1 from public.runner_club_requests where club_id=c.id and user_id=target) then raise exception '가입 신청이 없습니다.';end if;
     if exists(select 1 from public.runner_club_members where user_id=target) then raise exception '신청자가 이미 다른 모임에 가입했습니다.';end if;
     if (select count(*) from public.runner_club_members where club_id=c.id)>=4 then raise exception '모임 정원(4명)이 가득 찼습니다.';end if;
     insert into public.runner_club_members(user_id,club_id) values(target,c.id);delete from public.runner_club_requests where user_id=target;
     message_text=target||' 님의 가입을 승인했습니다.';kind='join';
    elsif p_action='reject' then delete from public.runner_club_requests where club_id=c.id and user_id=target;message_text='가입 신청을 거절했습니다.';kind='manage';
    elsif p_action in('permissions','transfer_lead','kick') then
     if not exists(select 1 from public.runner_club_members where user_id=target and club_id=c.id) or target=p_user then raise exception '다른 부원을 선택해 주세요.';end if;
     if p_action='permissions' then update public.runner_club_members set can_withdraw=coalesce((p_data->>'allowed')::boolean,false) where user_id=target;message_text=target||' 님 창고 출납 권한 변경';
     elsif p_action='transfer_lead' then update public.runner_clubs set owner_id=target where id=c.id;message_text=target||' 님에게 모임장을 위임했습니다.';
     else delete from public.runner_club_members where user_id=target;message_text=target||' 님을 내보냈습니다.';end if;kind='manage';
    elsif p_action='post' then
     nonce=coalesce(p_data->>'request','');parent=(p_data->>'parent')::bigint;
     if char_length(nonce) not between 8 and 100 or char_length(btrim(coalesce(p_data->>'body',''))) not between 1 and 2000 or char_length(coalesce(p_data->>'title',''))>60 then raise exception '게시글 제목은 60자, 내용은 1~2000자입니다.';end if;
     if parent is not null and not exists(select 1 from public.runner_club_posts where id=parent and club_id=c.id and parent_id is null) then raise exception '원글이 없습니다.';end if;
     if not exists(select 1 from public.runner_club_posts where user_id=p_user and request_id=nonce) then
      if (select count(*) from public.runner_club_posts where user_id=p_user and created_at>now()-interval '1 minute')>=10 then raise exception '잠시 후 다시 글을 남겨 주세요.';end if;
      insert into public.runner_club_posts(club_id,user_id,title,body,parent_id,request_id) values(c.id,p_user,left(coalesce(p_data->>'title',''),60),btrim(p_data->>'body'),parent,nonce);message_text=case when parent is null then '게시판에 글을 남겼습니다.' else '게시판에 댓글을 남겼습니다.' end;kind='board';
     end if;
    elsif p_action='delete_post' then
     delete from public.runner_club_posts where id=(p_data->>'id')::bigint and club_id=c.id and (user_id=p_user or c.owner_id=p_user);
     if not found then raise exception '본인 글 또는 모임장만 삭제할 수 있습니다.';end if;message_text='게시글을 삭제했습니다.';kind='board';
    elsif p_action='room_edit' then
     if coalesce(p_data->>'style','') not in('lantern','book','moon') or char_length(coalesce(p_data->>'text',''))>1000 then raise exception '모임방 꾸미기를 확인해 주세요.';end if;
     update public.runner_clubs set room_style=p_data->>'style',room_text=p_data->>'text' where id=c.id;message_text='모임방 꾸미기를 변경했습니다.';kind='room';
    end if;
   end if;
  elsif p_action<>'snapshot' then raise exception 'CLUB_ACTION';end if;
  if message_text is not null then
   select * into m from public.runner_club_members where user_id=p_user;
   pid=coalesce(m.club_id,before_member.club_id,c.id);
   if exists(select 1 from public.runner_clubs where id=pid) then insert into public.runner_club_logs(club_id,user_id,who,kind,body) values(pid,p_user,actor_name,kind,message_text);end if;
  end if;
 end if;
 r=public.runner_club_core(p_user,p_token,'snapshot',p_data);
 select * into m from public.runner_club_members where user_id=p_user;
 if m.user_id is not null then
  select * into c from public.runner_clubs where id=m.club_id;
  r=jsonb_set(r,'{mine}',(r->'mine')||jsonb_build_object('notice',c.notice,'join_mode',c.join_mode,'room_lv',c.room_lv,'room_style',c.room_style,'room_text',c.room_text,'can_withdraw',m.can_withdraw or c.owner_id=p_user,'donated',case when m.donated_day=today then m.donated else 0 end));
  select coalesce(jsonb_agg(to_jsonb(q) order by q.joined_at,q.user_id),'[]') into roster from
   (select cm.user_id,coalesce(nullif(a.name,''),a.id) as name,cm.joined_at,cm.contribution,cm.can_withdraw,coalesce((a.save->>'lvl')::integer,1) as lvl,cm.attended=today as attended from public.runner_club_members cm join public.accounts a on a.id=cm.user_id where cm.club_id=c.id) q;
  r=jsonb_set(r,'{members}',roster);
  if detail then
   select coalesce(jsonb_agg(to_jsonb(q) order by q.id desc),'[]') into posts from (select p.id,p.user_id,coalesce(nullif(a.name,''),a.id) as name,p.title,p.body,p.parent_id,p.created_at from public.runner_club_posts p join public.accounts a on a.id=p.user_id where p.club_id=c.id order by p.id desc limit 150) q;
   select coalesce(jsonb_agg(to_jsonb(q) order by q.id desc),'[]') into logs from (select lg.id,lg.who,lg.kind,lg.body,lg.created_at from public.runner_club_logs lg where lg.club_id=c.id order by lg.id desc limit 100) q;
   if c.owner_id=p_user then
    select coalesce(jsonb_agg(to_jsonb(q) order by q.created_at),'[]') into pending from (select cr.user_id,coalesce(nullif(a.name,''),a.id) as name,cr.created_at from public.runner_club_requests cr join public.accounts a on a.id=cr.user_id where cr.club_id=c.id order by cr.created_at limit 100) q;
   end if;
   r=r||jsonb_build_object('vault',c.vault,'posts',posts,'logs',logs,'requests',coalesce(pending,'[]'));
  end if;
 end if;
 if detail then
  select coalesce(jsonb_agg(to_jsonb(q) order by q.xp desc,q.id),'[]') into directory from
   (select rc.id,rc.name,rc.intro,rc.owner_id,coalesce(nullif(oa.name,''),oa.id) as owner_name,rc.xp,least(10,1+rc.xp/100) as lv,rc.join_mode,rc.created_at,count(cm.user_id) as members,coalesce(sum((a.save->>'lvl')::integer),0) as level_sum,exists(select 1 from public.runner_club_requests where club_id=rc.id and user_id=p_user) as applied
    from public.runner_clubs rc join public.accounts oa on oa.id=rc.owner_id left join public.runner_club_members cm on cm.club_id=rc.id left join public.accounts a on a.id=cm.user_id group by rc.id,oa.name,oa.id order by rc.xp desc,rc.id limit 200) q;
  r=jsonb_set(r,'{clubs}',directory);
 end if;
 return r||extra||jsonb_build_object('ok',true,'version',2,'inventory',inventory,'message',message_text);
end $$;
